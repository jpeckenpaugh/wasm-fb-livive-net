#!/usr/bin/env python3
"""Preprocess bundled images into C arrays (no decoder needed in the guest).

Deterministic by construction: inputs are sorted, output contains no
timestamps, and the resize filter is fixed. Runs inside the toolchain image,
which pins Pillow.

    python3 tools/prepare_assets.py --assets assets --out build/gen

Writes:
    build/gen/assets_gen.h   image table + dimensions + ASSET_COUNT
    build/gen/assets_gen.c   g_images[] / g_thumbs[] tables
    build/gen/asset_N.c      one translation unit per image (parallel builds)
"""
import argparse
import glob
import os
import sys

from PIL import Image, ImageOps

MAIN_SIZE = (480, 360)   # 4:3, matches UI_MAIN_W/UI_MAIN_H so the hero blits 1:1
THUMB_SIZE = (96, 72)    # matches UI_TH_W/UI_TH_H
EXPECTED = 5
BACKGROUND = (0x20, 0x20, 0x20)
HEX = ["0x%02x" % i for i in range(256)]


def c_array(name, data):
    lines = ["const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 32):
        lines.append("    " + ",".join(HEX[b] for b in data[i:i + 32]) + ",")
    lines.append("};")
    return "\n".join(lines)


def flatten(image, size):
    """Fit/crop to the target size and composite onto an opaque background."""
    fitted = ImageOps.fit(image, size, Image.Resampling.LANCZOS, centering=(0.5, 0.5))
    canvas = Image.new("RGBA", size, BACKGROUND + (255,))
    canvas.alpha_composite(fitted)
    return canvas


def find_sources(assets_dir):
    patterns = ("*.png", "*.jpg", "*.jpeg")
    paths = []
    for pattern in patterns:
        paths.extend(glob.glob(os.path.join(assets_dir, pattern)))
    return sorted(paths)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--assets", default="assets")
    parser.add_argument("--out", default="build/gen")
    args = parser.parse_args()

    sources = find_sources(args.assets)
    if len(sources) != EXPECTED:
        sys.exit("expected %d images in %s, found %d: %s"
                 % (EXPECTED, args.assets, len(sources), sources))

    os.makedirs(args.out, exist_ok=True)

    for index, path in enumerate(sources):
        with Image.open(path) as source:
            image = source.convert("RGBA")

        hero = flatten(image, MAIN_SIZE)
        thumb = (hero.convert("RGB")
                 .resize(THUMB_SIZE, Image.Resampling.LANCZOS)
                 .convert("RGBA"))

        parts = [
            '#include "assets_gen.h"',
            "",
            c_array("asset_%d_main" % index, hero.tobytes()),
            "",
            c_array("asset_%d_thumb" % index, thumb.tobytes()),
            "",
        ]
        with open(os.path.join(args.out, "asset_%d.c" % index), "w") as handle:
            handle.write("\n".join(parts))
        print("asset_%d <- %s" % (index, os.path.basename(path)))

    header = """/* Generated by tools/prepare_assets.py - do not edit. */
#ifndef ASSETS_GEN_H
#define ASSETS_GEN_H

#include <stdint.h>

#define ASSET_COUNT %d
#define ASSET_MAIN_W %d
#define ASSET_MAIN_H %d
#define ASSET_THUMB_W %d
#define ASSET_THUMB_H %d

typedef struct {
    const uint8_t *px;
    int w;
    int h;
} image_t;

extern const image_t g_images[ASSET_COUNT];
extern const image_t g_thumbs[ASSET_COUNT];

#endif /* ASSETS_GEN_H */
""" % (EXPECTED, MAIN_SIZE[0], MAIN_SIZE[1], THUMB_SIZE[0], THUMB_SIZE[1])

    with open(os.path.join(args.out, "assets_gen.h"), "w") as handle:
        handle.write(header)

    externs = "\n".join(
        "extern const unsigned char asset_%d_main[];\n"
        "extern const unsigned char asset_%d_thumb[];" % (i, i)
        for i in range(EXPECTED))
    mains = "\n".join(
        "    { asset_%d_main, ASSET_MAIN_W, ASSET_MAIN_H }," % i for i in range(EXPECTED))
    thumbs = "\n".join(
        "    { asset_%d_thumb, ASSET_THUMB_W, ASSET_THUMB_H }," % i for i in range(EXPECTED))

    table = """/* Generated by tools/prepare_assets.py - do not edit. */
#include "assets_gen.h"

%s

const image_t g_images[ASSET_COUNT] = {
%s
};

const image_t g_thumbs[ASSET_COUNT] = {
%s
};
""" % (externs, mains, thumbs)

    with open(os.path.join(args.out, "assets_gen.c"), "w") as handle:
        handle.write(table)

    total = EXPECTED * (MAIN_SIZE[0] * MAIN_SIZE[1] + THUMB_SIZE[0] * THUMB_SIZE[1]) * 4
    print("generated %d assets, %d bytes raw RGBA" % (EXPECTED, total))


if __name__ == "__main__":
    main()
