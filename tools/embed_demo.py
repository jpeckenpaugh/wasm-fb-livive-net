#!/usr/bin/env python3
"""Embed demo/* into the guest so the File Manager can list source files."""
import argparse
import pathlib


def c_string(text: str) -> str:
    out = []
    for line in text.split("\n"):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('        "%s\\n"' % escaped)
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", dest="src", default="demo")
    ap.add_argument("--out", dest="out", default="build/gen")
    args = ap.parse_args()

    files = sorted(p for p in pathlib.Path(args.src).iterdir() if p.is_file())
    outdir = pathlib.Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    entries = []
    for p in files:
        entries.append(
            '    { "%s",\n%s\n    },' % (p.name, c_string(p.read_text()))
        )

    (outdir / "demo_gen.h").write_text(
        "/* Generated by tools/embed_demo.py - do not edit. */\n"
        "#ifndef DEMO_GEN_H\n#define DEMO_GEN_H\n\n"
        "typedef struct {\n"
        "    const char *name;\n"
        "    const char *text;\n"
        "} demo_file_t;\n\n"
        "#define DEMO_FILE_COUNT %d\n"
        "extern const demo_file_t k_demo_files[DEMO_FILE_COUNT];\n\n"
        "#endif /* DEMO_GEN_H */\n" % len(entries)
    )
    (outdir / "demo_gen.c").write_text(
        '/* Generated by tools/embed_demo.py - do not edit. */\n'
        '#include "demo_gen.h"\n\n'
        "const demo_file_t k_demo_files[DEMO_FILE_COUNT] = {\n"
        + "\n".join(entries)
        + "\n};\n"
    )
    print("embedded %d demo files" % len(entries))


if __name__ == "__main__":
    main()
