#!/usr/bin/env python3
"""Embed ABOUT.md into the guest as a C string.

Keeps one source of truth: the markdown at the repo root is what GitHub shows
and what the Preview app renders.
"""
import argparse
import pathlib


def emit(text: str) -> str:
    lines = text.split("\n")
    out = []
    for i, line in enumerate(lines):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % escaped)
    return "const char k_about_md[] =\n" + "\n".join(out) + ";\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="src", default="ABOUT.md")
    ap.add_argument("--out", dest="out", default="build/gen")
    args = ap.parse_args()

    text = pathlib.Path(args.src).read_text()
    outdir = pathlib.Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    (outdir / "about_gen.h").write_text(
        "/* Generated by tools/embed_about.py - do not edit. */\n"
        "#ifndef ABOUT_GEN_H\n"
        "#define ABOUT_GEN_H\n\n"
        "extern const char k_about_md[];\n\n"
        "#endif /* ABOUT_GEN_H */\n"
    )
    (outdir / "about_gen.c").write_text(
        '/* Generated by tools/embed_about.py - do not edit. */\n'
        '#include "about_gen.h"\n\n' + emit(text)
    )
    print("embedded %s (%d bytes)" % (args.src, len(text)))


if __name__ == "__main__":
    main()
