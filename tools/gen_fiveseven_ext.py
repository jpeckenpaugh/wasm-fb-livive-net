def build_latin_sheet(filename, title, cp_start, cp_end):
    out = [f"# FiveSeven - {title} (U+{cp_start:04X}..U+{cp_end:04X})", ""]
    count = 0
    for cp in range(cp_start, cp_end + 1):
        ch = chr(cp)
        if cp in SPECIAL_LATIN:
            rows, dy = SPECIAL_LATIN[cp]
        else:
            res = compose_latin_diacritic(ch)
            assert res is not None, f"Unhandled Latin U+{cp:04X} ({ch})"
            rows, dy = res
        lbl = unicodedata.name(ch, f"U+{cp:04X}").split()[0] if cp in (0x00A0, 0x00AD) else ch
        hdr = f"@U+{cp:04X} {lbl}" + (f" dy={dy}" if dy else "")
        out.append(hdr)
        out.extend(rows_to_str(rows))
        out.append("")
        count += 1
    with open(os.path.join(ROOT, filename), "w") as fh:
        fh.write("\n".join(out))
    return count


