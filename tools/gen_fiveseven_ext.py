ROOT = os.path.join(os.path.dirname(__file__), "..", "v2", "glyphs", "fiveseven")

# Load Basic Latin base glyphs from 0020-007E_basic_latin.txt
BASE = {}
BASE_DY = {}
with open(os.path.join(ROOT, "0020-007E_basic_latin.txt")) as fh:
    lines = [l.rstrip("\n") for l in fh]
i = 0
while i < len(lines):
    l = lines[i]
    if l.startswith("@U+"):
        parts = l[3:].split()
        cp = int(parts[0], 16)
        dy = 0
        for p in parts[1:]:
            if p.startswith("dy="):
                dy = int(p.split("=")[1])
        rows = []
        for r in range(7):
            row_s = lines[i + 1 + r]
            mask = 0
            for c, ch in enumerate(row_s):
                if ch == "#":
                    mask |= 1 << (4 - c)
            rows.append(mask)
        BASE[chr(cp)] = rows
        BASE_DY[chr(cp)] = dy
        i += 8
    else:
        i += 1


def rows_to_str(rows):
    return ["".join("#" if (r & (1 << (4 - c))) else "." for c in range(5)) for r in rows]


def str_to_rows(strs):
    assert len(strs) == 7
    out = []
    for s in strs:
        assert len(s) == 5, f"bad row {s!r}"
        m = 0
        for c, ch in enumerate(s):
            if ch == "#":
                m |= 1 << (4 - c)
        out.append(m)
    return out


