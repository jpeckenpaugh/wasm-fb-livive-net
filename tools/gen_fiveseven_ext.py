def compose_latin_diacritic(ch):
    decomp = unicodedata.normalize("NFD", ch)
    if len(decomp) != 2:
        return None
    base, mark = decomp[0], ord(decomp[1])
    if base == "ı":
        base = "i"
    if base not in BASE:
        return None

    # Top diacritic
    if mark in TOP_ACCENT:
        r0, r1 = TOP_ACCENT[mark]
        if base in UPPER_5:
            return ([r0, r1] + UPPER_5[base], 0)
        if base in TALL_LOWER_5:
            return ([r0, r1] + TALL_LOWER_5[base], 0)
        if base == "i":
            return ([r0, r1, 0x0C, 0x04, 0x04, 0x04, 0x0E], 0)
        if base == "j":
            return ([r0, r1, 0x06, 0x02, 0x02, 0x12, 0x0C], 1)
        if base == "g":
            return ([r0, r1, 0x0F, 0x11, 0x0F, 0x01, 0x0E], 2)
        if base == "y":
            return ([r0, r1, 0x11, 0x11, 0x0F, 0x01, 0x0E], 2)
        b_rows = list(BASE[base])
        return ([r0, r1] + b_rows[2:], BASE_DY[base])

    # Bottom diacritic: cedilla (0x0327), ogonek (0x0328), comma/cedilla below (0x0326)
    if mark in (0x0327, 0x0328, 0x0326):
        tail = [0x04, 0x08] if mark != 0x0328 else [0x04, 0x06]
        if base in UPPER_5:
            return (UPPER_5[base] + tail, 2)
        if base in TALL_LOWER_5:
            return (TALL_LOWER_5[base] + tail, 2)
        b_rows = list(BASE[base])
        return (b_rows[2:] + tail, 2)

    return None


