def write_dict_sheet(filename, title, table):
    out = [f"# FiveSeven - {title}", ""]
    for cp in sorted(table.keys()):
        rows, dy = table[cp]
        ch = chr(cp)
        hdr = f"@U+{cp:04X} {ch}" + (f" dy={dy}" if dy else "")
        out.append(hdr)
        out.extend(rows_to_str(rows))
        out.append("")
    with open(os.path.join(ROOT, filename), "w") as fh:
        fh.write("\n".join(out))
    return len(table)


