//! Extensible Bitmap Font Engine (`font.rs`).
//!
//! Architecture for multi-locale / multi-script testing:
//! - A [`FontSheet`] defines a character range (`first_code..=last_code`), cell
//!   dimensions (`glyph_w x glyph_h`), and a lookup function (`glyph_rows`) that
//!   maps a Unicode scalar (`u32`) to its row bitmasks.
//! - [`FIVESEVEN_US_LATIN`] is the baseline 5x7 US-English / Basic Latin (`U+0020..=U+007E`)
//!   font sheet (95 glyphs, 35 bits per glyph).
//! - Additional language / script sheets (e.g. Latin-1 Supplement `U+00A0..=U+00FF`
//!   for Spanish `ñ á é í ó ú ¿ ¡`, or CJK / Mandarin fixed-grid sheets) plug into
//!   the same [`FontSheet`] registry without changing the layout or style engine.
//!
//! Glyph bitmaps and metrics live in [`crate::glyph`] (generated by `build.rs` from
//! `v2/glyphs/`). Strings are decoded as UTF-8 `char`s; Icons32 glyphs (`U+E000..`
//! and aliases such as `U+2302 ⌂`) may appear inline in text.
//!
//! Two spacing modes:
//! - **Monospace** ([`draw_str`], [`text_width`]): fixed `6 * scale` advance per
//!   char (inline icons take 2 cells). Used by code / file previews that compute
//!   columns from the cell grid.
//! - **Proportional** ([`draw_str_prop`], [`text_width_prop`]): blank columns are
//!   trimmed from each glyph (`i`, `l`, `!` become narrow) and inline icons take a
//!   square cell. Intended for UI labels.
//!
//! In both modes glyphs carry a `dy` bump (e.g. `g j p q y ,` hang below the 7-row
//! cell by 1-2 rows), so line pitch should allow `9 * scale` of ink height.

use crate::fb::Framebuffer;
use crate::glyph::{self, Glyph, TextGlyph, MISSING_ROWS};

pub const GLYPH_W: i32 = 5;
pub const GLYPH_H: i32 = 7;
/// Rows a bumped glyph may extend below the cell (descender depth).
pub const DESCENT: i32 = 2;
pub const GLYPH_COUNT: usize = glyph::FIVESEVEN_GLYPH_COUNT;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum FontStyle {
    Regular = 0,
    Bold = 1,
    Italic = 2,
    Matrix = 3,
    Underline = 4,
}

/// Extensible descriptor for a character block / locale font sheet.
pub struct FontSheet {
    pub id: &'static str,
    pub locale: &'static str,
    pub range_label: &'static str,
    pub first_code: u32,
    pub last_code: u32,
    pub glyph_w: u8,
    pub glyph_h: u8,
    pub glyph_count: usize,
    pub lookup: fn(u32) -> Option<[u8; 7]>,
}

pub const FIVESEVEN_US_LATIN: FontSheet = FontSheet {
    id: "FiveSeven",
    locale: "Multi-Script (Latin / Greek / Cyrillic / Symbols)",
    range_label: "532 Glyphs + 32 Icons (UTF-8)",
    first_code: 0x0020,
    last_code: 0x26FF,
    glyph_w: 5,
    glyph_h: 7,
    glyph_count: GLYPH_COUNT,
    lookup: lookup_us_latin,
};

/// Registry of compiled-in font sheets.
/// To test Spanish (`es-ES`, `U+00A0..U+00FF`) or Mandarin (`zh-CN`, `U+4E00..`),
/// register an additional [`FontSheet`] entry here.
pub const FONT_REGISTRY: &[FontSheet] = &[FIVESEVEN_US_LATIN];

/// Monospace advance per character cell.
#[inline]
pub const fn char_advance(scale: i32) -> i32 {
    (GLYPH_W + 1) * scale
}

/// Width (in source pixels at scale 1) of an inline icon cell: square, one text
/// cell tall.
const INLINE_ICON: i32 = GLYPH_H;
/// Proportional advance for blank glyphs (SPACE).
const BLANK_ADVANCE: i32 = 3;

#[inline]
fn mono_cells(cp: u32) -> i32 {
    match glyph::resolve(cp) {
        Glyph::Icon(_) => 2,
        _ => 1,
    }
}

/// Monospace string width in pixels (no trailing gap).
pub fn text_width(s: &str, scale: i32) -> i32 {
    let cells: i32 = s.chars().map(|c| mono_cells(c as u32)).sum();
    if cells <= 0 {
        0
    } else {
        cells * char_advance(scale) - scale
    }
}

/// Proportional advance (including the 1-column gap) of a resolved glyph, in
/// source pixels at scale 1.
fn prop_advance_units(g: &Glyph) -> i32 {
    match g {
        Glyph::Text(t) if t.ink_w == 0 => BLANK_ADVANCE,
        Glyph::Text(t) => t.ink_w as i32 + 1,
        Glyph::Icon(_) => INLINE_ICON + 1,
        Glyph::Missing => GLYPH_W + 1,
    }
}

/// Proportional advance of a single character at `scale`.
pub fn char_advance_prop(ch: char, scale: i32) -> i32 {
    prop_advance_units(&glyph::resolve(ch as u32)) * scale
}

/// Proportional string width in pixels (no trailing gap).
pub fn text_width_prop(s: &str, scale: i32) -> i32 {
    let units: i32 = s
        .chars()
        .map(|c| prop_advance_units(&glyph::resolve(c as u32)))
        .sum();
    if units <= 0 {
        0
    } else {
        units * scale - scale
    }
}

pub fn draw_str(fb: &mut Framebuffer, x: i32, y: i32, s: &str, scale: i32, color: u32) {
    draw_str_styled(fb, x, y, s, scale, FontStyle::Regular, color);
}

/// Monospace styled string.
pub fn draw_str_styled(
    fb: &mut Framebuffer,
    mut x: i32,
    y: i32,
    s: &str,
    scale: i32,
    style: FontStyle,
    color: u32,
) {
    if scale <= 0 {
        return;
    }
    let adv = char_advance(scale);
    for ch in s.chars() {
        match glyph::resolve(ch as u32) {
            Glyph::Icon(i) => {
                // Centre the square icon in its 2-cell slot.
                let slot = 2 * adv - scale;
                let sz = INLINE_ICON * scale;
                glyph::draw_icon_index(fb, x + (slot - sz) / 2, y, i, sz, color);
                x += 2 * adv;
            }
            Glyph::Text(t) => {
                draw_text_glyph(fb, x, y, &t, false, scale, style, color);
                x += adv;
            }
            Glyph::Missing => {
                draw_text_glyph(fb, x, y, &missing(), false, scale, style, color);
                x += adv;
            }
        }
    }
}

pub fn draw_str_prop(fb: &mut Framebuffer, x: i32, y: i32, s: &str, scale: i32, color: u32) {
    draw_str_prop_styled(fb, x, y, s, scale, FontStyle::Regular, color);
}

/// Proportional styled string: glyphs are drawn shifted left by their blank
/// leading columns, then advance by ink width + 1 gap column.
pub fn draw_str_prop_styled(
    fb: &mut Framebuffer,
    mut x: i32,
    y: i32,
    s: &str,
    scale: i32,
    style: FontStyle,
    color: u32,
) {
    if scale <= 0 {
        return;
    }
    for ch in s.chars() {
        let g = glyph::resolve(ch as u32);
        match g {
            Glyph::Icon(i) => {
                glyph::draw_icon_index(fb, x, y, i, INLINE_ICON * scale, color);
            }
            Glyph::Text(t) => {
                draw_text_glyph(fb, x, y, &t, true, scale, style, color);
            }
            Glyph::Missing => {
                draw_text_glyph(fb, x, y, &missing(), false, scale, style, color);
            }
        }
        x += prop_advance_units(&g) * scale;
    }
}

#[allow(clippy::too_many_arguments)]
pub fn draw_str_centered(
    fb: &mut Framebuffer,
    rx: i32,
    ry: i32,
    rw: i32,
    rh: i32,
    s: &str,
    scale: i32,
    color: u32,
) {
    let tw = text_width(s, scale);
    let th = GLYPH_H * scale;
    let x = rx + (rw - tw) / 2;
    let y = ry + (rh - th) / 2;
    draw_str(fb, x, y, s, scale, color);
}

/// Proportional variant of [`draw_str_centered`].
#[allow(clippy::too_many_arguments)]
pub fn draw_str_prop_centered(
    fb: &mut Framebuffer,
    rx: i32,
    ry: i32,
    rw: i32,
    rh: i32,
    s: &str,
    scale: i32,
    color: u32,
) {
    let tw = text_width_prop(s, scale);
    let th = GLYPH_H * scale;
    draw_str_prop(fb, rx + (rw - tw) / 2, ry + (rh - th) / 2, s, scale, color);
}

pub fn draw_char(fb: &mut Framebuffer, x: i32, y: i32, ch: char, scale: i32, color: u32) {
    draw_char_styled(fb, x, y, ch, scale, FontStyle::Regular, color);
}

/// Draw one character in a monospace cell at `(x, y)`.
pub fn draw_char_styled(
    fb: &mut Framebuffer,
    x: i32,
    y: i32,
    ch: char,
    scale: i32,
    style: FontStyle,
    color: u32,
) {
    let mut buf = [0u8; 4];
    draw_str_styled(fb, x, y, ch.encode_utf8(&mut buf), scale, style, color);
}

fn missing() -> TextGlyph {
    TextGlyph {
        rows: &MISSING_ROWS,
        dy: 0,
        lsb: 0,
        ink_w: 5,
    }
}

/// Rasterize a 5x7 text glyph; in proportional mode blank leading columns are
/// trimmed, `t.dy` bumps rows down (descenders).
#[allow(clippy::too_many_arguments)]
fn draw_text_glyph(
    fb: &mut Framebuffer,
    x: i32,
    y: i32,
    t: &TextGlyph,
    proportional: bool,
    scale: i32,
    style: FontStyle,
    color: u32,
) {
    let trim = if proportional { t.lsb as i32 } else { 0 };
    let dot_size = match style {
        FontStyle::Matrix if scale > 1 => scale - 1,
        _ => scale,
    };
    let bold_extra = match style {
        FontStyle::Bold => (scale / 2).max(1),
        _ => 0,
    };
    let dy = t.dy as i32;

    for (row_idx, &mask) in t.rows.iter().enumerate() {
        if mask == 0 {
            continue;
        }
        let cell_row = row_idx as i32 + dy;
        let py = y + cell_row * scale;
        let shear_dx = match style {
            FontStyle::Italic => ((6 - cell_row) * scale) / 3,
            _ => 0,
        };
        for col in 0..5 {
            if (mask & (1 << (4 - col))) != 0 {
                let px = x + (col - trim) * scale + shear_dx;
                fb.fill(px, py, dot_size + bold_extra, dot_size, color);
            }
        }
    }

    if style == FontStyle::Underline {
        // Underline spans the glyph's advance: full cell in monospace, trimmed in
        // proportional mode (`trim` is only non-zero / ink-based there).
        let w = if proportional {
            prop_advance_units(&Glyph::Text(*t))
        } else {
            GLYPH_W + 1
        };
        let ul_y = y + GLYPH_H * scale + (scale / 2).max(1);
        fb.fill(x, ul_y, w * scale, scale.max(1), color);
    }
}

/// Resolve a Unicode codepoint to 5x7 rows (missing box when not a text glyph).
pub fn resolve_glyph(code: u32) -> [u8; 7] {
    match glyph::lookup_fiveseven(code) {
        Some(t) => *t.rows,
        None => MISSING_ROWS,
    }
}

fn lookup_us_latin(code: u32) -> Option<[u8; 7]> {
    glyph::lookup_fiveseven(code).map(|t| *t.rows)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn basic_latin_fully_covered() {
        for cp in 0x20u32..=0x7E {
            assert!(glyph::lookup_fiveseven(cp).is_some(), "U+{:04X}", cp);
        }
    }

    #[test]
    fn extended_scripts_and_symbols_covered() {
        for cp in 0x00A0u32..=0x017F {
            assert!(glyph::lookup_fiveseven(cp).is_some(), "Latin U+{:04X}", cp);
        }
        for c in [
            'ñ', 'É', 'ß', 'ł', 'Ω', 'π', 'λ', 'Ж', 'Я', 'д', '€', '∞', '┼', '█',
        ] {
            assert!(glyph::lookup_fiveseven(c as u32).is_some(), "{}", c);
        }
    }

    #[test]
    fn descenders_are_bumped() {
        for (c, dy) in [
            ('g', 2),
            ('p', 2),
            ('q', 2),
            ('y', 2),
            ('j', 1),
            (',', 1),
            ('a', 0),
        ] {
            assert_eq!(glyph::lookup_fiveseven(c as u32).unwrap().dy, dy, "{}", c);
        }
    }

    #[test]
    fn proportional_trims_thin_glyphs() {
        assert!(char_advance_prop('i', 1) < char_advance_prop('m', 1));
        assert_eq!(char_advance_prop('m', 1), 6);
        assert_eq!(char_advance_prop('!', 1), 2);
        assert!(text_width_prop("illicit", 1) < text_width("illicit", 1));
    }

    #[test]
    fn inline_icon_widths() {
        let home = "\u{E000}";
        assert_eq!(text_width(home, 1), 2 * char_advance(1) - 1);
        assert_eq!(text_width_prop(home, 1), INLINE_ICON);
        assert!(matches!(glyph::resolve(0x2302), Glyph::Icon(0)));
    }
}
